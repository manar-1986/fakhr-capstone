export function localizeGuide(guide: DisabilityGuide, locale: string): DisabilityGuide {
  if (!locale.startsWith("en")) return guide;
  const en = DISABILITY_GUIDES_EN[guide.id];
  if (!en) return guide;
  return { ...guide, ...en };
}

