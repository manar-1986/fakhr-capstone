import React from "react";
import { cleanup, fireEvent, render } from "@testing-library/react-native";
import HomeGlobalSearch from "../components/home/HomeGlobalSearch";
import { Platform } from "react-native";
let mockRTL = false;
let mockFetching = false;
let mockError = false;
const mockPush = jest.fn();
const mockRefetch = jest.fn();
jest.mock("expo-router", () => ({ useRouter: () => ({ push: mockPush }) }));
jest.mock("@react-navigation/native", () => ({ useIsFocused: () => true }));
jest.mock("@expo/vector-icons", () => ({ Ionicons: "Icon" }));
jest.mock("react-i18next", () => ({ useTranslation: () => ({ t: () => "Search" }) }));
jest.mock("../hooks/useI18nLayout", () => ({ useI18nLayout: () => ({ isRTL: mockRTL, align: mockRTL ? "right" : "left", dir: mockRTL ? "rtl" : "ltr" }) }));
jest.mock("../api/directory.api", () => ({ centersListQueryKey: () => ["centers"], getCenters: jest.fn() }));
jest.mock("@tanstack/react-query", () => ({ useQuery: () => ({ data: [], isFetching: mockFetching, isError: mockError, refetch: mockRefetch }) }));
beforeEach(() => { mockRTL = false; mockFetching = false; mockError = false; mockPush.mockClear(); mockRefetch.mockClear(); });
afterEach(() => { cleanup(); jest.restoreAllMocks(); });
test.each([true, false])("RTL=%s: focusing never navigates; typing, editing, clearing and selecting work", rtl => {
  mockRTL = rtl;
  const ui = render(<HomeGlobalSearch />);
  const input = ui.getByTestId("home-search-input");
  fireEvent.press(ui.getByTestId("home-search-field"));
  fireEvent(input, "focus");
  expect(mockPush).not.toHaveBeenCalled();
  fireEvent.changeText(input, rtl ? "هديل" : "Hadeel");
  fireEvent(input, "submitEditing");
  expect(mockPush).not.toHaveBeenCalled();
  fireEvent.press(ui.getByLabelText(rtl ? "د. هديل ياسين الفرس، الأطباء والمتخصصون" : "Dr. Hadeel Yassin Faras، Doctors & specialists"));
  expect(mockPush).toHaveBeenCalledWith({ pathname: "/(tabs)/directory/professional-details", params: { id: "doctor-hadeel-yassin-faras" } });
  fireEvent.changeText(input, "xyz-no-such-item");
  expect(ui.getByText(rtl ? "لم نعثر على نتائج. جرّب اسماً آخر أو كلمة أقصر." : "No results found. Try another name or a shorter search.")).toBeTruthy();
  fireEvent.press(ui.getByLabelText(rtl ? "مسح البحث" : "Clear search"), { stopPropagation: jest.fn() });
  expect(input.props.value).toBe("");
  expect(ui.queryByTestId("home-search-results")).toBeNull();
});
test("API loading and failures retain local results, and retry is available", () => {
  mockFetching = true;
  const ui = render(<HomeGlobalSearch />);
  fireEvent.changeText(ui.getByTestId("home-search-input"), "Wheelchair");
  expect(ui.getByText("Updating center results…")).toBeTruthy();
  expect(ui.getByText("Wheelchair")).toBeTruthy();
  mockFetching = false; mockError = true; ui.rerender(<HomeGlobalSearch />);
  expect(ui.getByText("Couldn’t update centers. Available local records are still searchable.")).toBeTruthy();
  fireEvent.press(ui.getByText("Retry")); expect(mockRefetch).toHaveBeenCalled();
  expect(ui.getByText("Wheelchair")).toBeTruthy();
});
test.each(["ios", "android", "web"] as const)("%s: editable input and product result navigation", os => {
  jest.replaceProperty(Platform, "OS", os);
  const ui = render(<HomeGlobalSearch />);
  const input = ui.getByTestId("home-search-input");
  expect(input.props.editable).not.toBe(false);
  expect(input.props.submitBehavior).toBe("submit");
  fireEvent.changeText(input, "Wheelchair");
  fireEvent.press(ui.getByLabelText("Wheelchair، Home products"));
  expect(mockPush).toHaveBeenCalledWith({ pathname: "/(tabs)/products/product-details", params: { id: "p-1" } });
});
