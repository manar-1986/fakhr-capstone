// Read-only projection of the SAME canonical records used by the Schools screen.
// Run with node scripts/exportSchoolDirectory.cjs; no database or network access.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
require.extensions['.ts'] = (module, filename) => {
  module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true },
  }).outputText, filename);
};
const directory = require(path.join(root, 'utils/institutionDirectory.ts'));
const labels = require(path.join(root, 'constants/institutionLabels.ts'));
const records = directory.filterInstitutions(directory.INSTITUTIONS, {})
  .filter(item => directory.institutionDirectoryCategory(item) === 'school');
const body = { schemaVersion: 1, category: 'school', sources: directory.INSTITUTION_SOURCES,
  disabilityLabels: labels.disabilityLabels, stageLabels: labels.stageLabels,
  governorateLabels: labels.governorateLabels, records };
const snapshot = { ...body, version: crypto.createHash('sha256').update(JSON.stringify(body)).digest('hex') };
const output = path.join(root, 'data/ai/schools.snapshot.json');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, JSON.stringify(snapshot, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'data/ai/schoolDirectoryVersion.ts'), `// Generated by exportSchoolDirectory.cjs\nexport const schoolDirectoryVersion = ${JSON.stringify(snapshot.version)};\n`);
console.log(`Exported ${records.length} canonical school records; version ${snapshot.version}`);
